def emit_motif_svg() -> str:
    """Procedural book-spine + leaf arcs — impact motif."""
    parts = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 400" fill="none">',
        "<defs>",
        '<linearGradient id="g" x1="0" y1="0" x2="1" y2="1">',
        '<stop offset="0%" stop-color="#5c1a2e"/>',
        '<stop offset="55%" stop-color="#7a2e45"/>',
        '<stop offset="100%" stop-color="#c4a35a"/>',
        "</linearGradient>",
        "</defs>",
    ]
    # book spines
    for i, x in enumerate((120, 155, 190, 225)):
        h = 140 + (i % 3) * 28
        y = 200 - h / 2
        parts.append(
            f'<rect x="{x}" y="{y:.1f}" width="22" height="{h:.1f}" rx="3" '
            f'stroke="url(#g)" stroke-width="2" opacity="{0.35 + i * 0.08}"/>'
        )
    # leaf arcs
    cx, cy = 200.0, 200.0
    for i in range(10):
        angle = i * (math.pi / 5) + 0.15
        r = 95 + (i % 3) * 22
        x = cx + math.cos(angle) * r
        y = cy + math.sin(angle) * r
        mx = cx + math.cos(angle + 0.55) * (r * 0.55)
        my = cy + math.sin(angle + 0.55) * (r * 0.55)
        parts.append(
            f'<path d="M{cx:.1f},{cy:.1f} Q{mx:.1f},{my:.1f} {x:.1f},{y:.1f}" '
            f'stroke="url(#g)" stroke-width="{1.4 + (i % 3) * 0.35}" '
            f'stroke-linecap="round" opacity="{0.28 + (i % 4) * 0.08}"/>'
        )
    for i in range(7):
        a = i * (math.pi / 3.5) + 0.4
        r = 130 + (i % 2) * 25
        x = cx + math.cos(a) * r
        y = cy + math.sin(a) * r
        parts.append(
            f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{3.5 + (i % 3)}" '
            f'fill="url(#g)" opacity="0.4"/>'
        )
    parts.append(f'<circle cx="{cx}" cy="{cy}" r="7" fill="url(#g)" opacity="0.65"/>')
    parts.append("</svg>")
    return "\n".join(parts)


