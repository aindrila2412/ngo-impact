def to_ts_module(data: dict) -> str:
    payload = json.dumps(data, ensure_ascii=False, indent=2)
    return (
        "/* Generated by build_content.py — do not edit by hand */\n"
        f"export const content = {payload} as const;\n"
        "export type SiteContent = typeof content;\n"
    )


def main() -> None:
    data = json.loads(CONTENT_PATH.read_text(encoding="utf-8"))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    PUBLIC_DIR.mkdir(parents=True, exist_ok=True)

    OUT_TS.write_text(to_ts_module(data), encoding="utf-8")
    OUT_HTML.write_text(build_sections(data), encoding="utf-8")
    OUT_VARS.write_text(emit_palette_css(), encoding="utf-8")
    OUT_SVG.write_text(emit_motif_svg(), encoding="utf-8")
    (OUT_DIR / "content.snapshot.json").write_text(
        json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(f"Wrote {OUT_TS.relative_to(ROOT)}")
    print(f"Wrote {OUT_HTML.relative_to(ROOT)}")
    print(f"Wrote {OUT_VARS.relative_to(ROOT)}")
    print(f"Wrote {OUT_SVG.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
